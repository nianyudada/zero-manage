// Helper to get coordinates for any province, city, or district
export function getCoordinates(
  province?: string | null,
  city?: string | null,
  district?: string | null
): LatLng {
  // 1. Check composite key: province_city_district
  if (province && city && district) {
    const pcdKey = `${province}_${city}_${district}`;
    if (COMPOSITE_DISTRICT_COORDINATES[pcdKey]) {
      return COMPOSITE_DISTRICT_COORDINATES[pcdKey];
    }
  }

  // 2. Check composite key: city_district
  if (city && district) {
    const cdKey = `${city}_${district}`;
    if (COMPOSITE_DISTRICT_COORDINATES[cdKey]) {
      return COMPOSITE_DISTRICT_COORDINATES[cdKey];
    }
  }

  // 3. Check simple district
  if (district && DISTRICT_COORDINATES[district]) {
    return DISTRICT_COORDINATES[district];
  }

  // 4. Check city
  if (city && CITY_COORDINATES[city]) {
    return CITY_COORDINATES[city];
  }

  // 5. Check province
  if (province && PROVINCE_COORDINATES[province]) {
    return PROVINCE_COORDINATES[province];
  }

  // Default to central China (near Henan/Xi'an)
  return { lat: 34.3416, lng: 108.9398 };
}
